NO_APPROVAL = [
    "No in-system approval applies; output is verified through the Garrison review workbook (F04-004) and user acceptance testing (F05-005).",
    "There is no approver inbox.",
    "No approval decision applies on this feature.",
]


def dev_journey(who, how, edit, dev_hist, lead_hist):
    return [who, how, edit, *NO_APPROVAL, dev_hist, lead_hist]


def page_journey(source, how, edit, uat="Garrison approves the pages on staging during user acceptance testing (F05-005)."):
    return [source, how, edit, *NO_APPROVAL[:1],
            "Not applicable for visitors; there is no approver inbox.",
            "No approval decision applies on public pages.",
            "Not applicable for visitors.", uat]


def signoff_journey(who, how, edit, submit, decision, maker_hist, audit_hist):
    return [who, how, edit, submit, "There is no in-system inbox; the delivery lead tracks the review round and open comments in a shared list.",
            decision, maker_hist, audit_hist]


